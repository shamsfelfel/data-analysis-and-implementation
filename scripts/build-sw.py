#!/usr/bin/env python3
"""Write sw.js with a precache list of everything the site is made of.

The course has to work with the network off -- that is the whole point of
shipping it as an installable app rather than a web page -- so the service
worker precaches every page, stylesheet, script, question bank and icon on
install rather than filling a cache as the reader wanders.

The list is generated instead of hand-kept because a page added to the course
and forgotten here would be a page that silently fails offline, which is the
hardest kind of bug to notice: everything works at your desk.

Run it after build.py, whenever a file is added or removed:

    python3 scripts/build-sw.py

The cache name carries the date and a counter, so writing a new worker
invalidates every old cache and installed readers pick up the change.
"""
import datetime
import io
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# Directories whose entire contents ship, and the loose files at the root.
DIRS = ["assets", "chapters", "lessons", "tests", "exams", "labs", "glossary", "icons", "downloads"]
FILES = ["index.html", "manifest.webmanifest"]

SKIP_SUFFIX = (".py", ".md", ".map")
SKIP_NAMES = {".DS_Store", "Thumbs.db"}

TEMPLATE = u'''/* ============================================================
   Service worker -- generated by scripts/build-sw.py, do not edit.

   Every file the course is made of is precached on install, so
   after one visit the whole thing opens with the network off and
   the browser will offer to install it as an app.

   Navigations are network-first: online, a reader always gets the
   page as it is on the server, and the copy that answered is put
   back in the cache; offline, the cached page answers instead, and
   a page never seen before falls back to the course home rather
   than a browser error.

   Assets are cache-first -- they are versioned by this file's
   cache name, so there is nothing to revalidate.

   CACHE changes on every build. The activate handler deletes every
   other cache, which is what makes a stale chapter impossible.
   ============================================================ */
'use strict';

var CACHE = '%(cache)s';

/* Paths are relative to this file, which sits at the site root, so
   they resolve the same whether the course is served from a domain
   root or from a GitHub Pages project subpath. */
var PRECACHE = [
  "./",
%(assets)s
];

self.addEventListener('install', function (event) {
  event.waitUntil(
    caches.open(CACHE).then(function (cache) {
      /* Added one at a time: addAll rejects as a unit, so a single
         404 would leave the worker uninstalled and the course with
         no offline support at all. */
      return Promise.all(PRECACHE.map(function (url) {
        return cache.add(new Request(url, { cache: 'reload' }))['catch'](function () {});
      }));
    }).then(function () { return self.skipWaiting(); })
  );
});

self.addEventListener('activate', function (event) {
  event.waitUntil(
    caches.keys().then(function (keys) {
      return Promise.all(keys.map(function (k) {
        return k === CACHE ? null : caches['delete'](k);
      }));
    }).then(function () { return self.clients.claim(); })
  );
});

self.addEventListener('message', function (event) {
  if (event.data === 'skipWaiting') self.skipWaiting();
});

self.addEventListener('fetch', function (event) {
  var req = event.request;
  if (req.method !== 'GET') return;

  var url = new URL(req.url);
  if (url.origin !== self.location.origin) return;

  if (req.mode === 'navigate') {
    event.respondWith(
      fetch(req).then(function (res) {
        if (res && res.ok) {
          var copy = res.clone();
          caches.open(CACHE).then(function (c) { c.put(req, copy); });
        }
        return res;
      })['catch'](function () {
        return caches.match(req).then(function (hit) {
          if (hit) return hit;
          /* A page that was never cached, with no network to fetch it.
             Answering with the home page's HTML would render it under
             the URL that was asked for, where all of its relative links
             and assets resolve one directory too deep - an unstyled page
             with a broken menu. Redirecting instead lands the reader on
             the real home page, which is cached. */
          return Response.redirect(self.registration.scope, 302);
        });
      })
    );
    return;
  }

  event.respondWith(
    caches.match(req).then(function (hit) {
      if (hit) return hit;
      return fetch(req).then(function (res) {
        if (res && res.status === 200 && res.type === 'basic') {
          var copy = res.clone();
          caches.open(CACHE).then(function (c) { c.put(req, copy); });
        }
        return res;
      });
    })
  );
});
'''


def walk():
    """Every shippable file, as a site-root-relative path, sorted."""
    out = []
    for name in FILES:
        if os.path.exists(os.path.join(ROOT, name)):
            out.append(name)
    for d in DIRS:
        base = os.path.join(ROOT, d)
        if not os.path.isdir(base):
            continue
        for dirpath, dirnames, filenames in os.walk(base):
            dirnames[:] = [x for x in dirnames if not x.startswith(".")]
            for f in sorted(filenames):
                if f in SKIP_NAMES or f.endswith(SKIP_SUFFIX) or f.startswith("."):
                    continue
                full = os.path.join(dirpath, f)
                rel = os.path.relpath(full, ROOT).replace(os.sep, "/")
                out.append(rel)
    return sorted(set(out))


def next_cache_name(today):
    """A fresh name every build: same day twice means bump the counter."""
    path = os.path.join(ROOT, "sw.js")
    n = 1
    if os.path.exists(path):
        current = io.open(path, encoding="utf-8").read()
        m = re.search(r"var CACHE = 'da-(\d{8})-(\d+)'", current)
        if m and m.group(1) == today:
            n = int(m.group(2)) + 1
    return "da-%s-%d" % (today, n)


def main():
    check = "--check" in sys.argv
    files = walk()
    if not files:
        print("nothing to precache -- run build.py first", file=sys.stderr)
        return 1

    today = datetime.date.today().strftime("%Y%m%d")
    path = os.path.join(ROOT, "sw.js")

    assets = "\n".join('  "%s"%s' % (f, "," if i < len(files) - 1 else "")
                       for i, f in enumerate(files))

    if check:
        current = io.open(path, encoding="utf-8").read() if os.path.exists(path) else ""
        listed = re.findall(r'^  "([^"]+)",?$', current, re.M)
        listed = [x for x in listed if x != "./"]
        missing = sorted(set(files) - set(listed))
        gone = sorted(set(listed) - set(files))
        if missing or gone:
            if missing:
                print("sw.js does not precache: %s" % ", ".join(missing), file=sys.stderr)
            if gone:
                print("sw.js precaches files that no longer exist: %s"
                      % ", ".join(gone), file=sys.stderr)
            return 1
        print("sw.js precaches all %d files" % len(files))
        return 0

    text = TEMPLATE % {"cache": next_cache_name(today), "assets": assets}
    io.open(path, "w", encoding="utf-8", newline="\n").write(text)
    print("wrote sw.js -- %d files precached" % (len(files) + 1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
